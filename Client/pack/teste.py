
strings = [
    ([0x1E, 0x3F, 0x0A, 0xE7, 0x5E, 0xD6, 0x09, 0xA9, 0x13, 0x09],
     0xDF390927, 0x9D3FE36F),

    ([0x02, 0x33, 0x79, 0xBF, 0x18, 0x3B, 0x3E, 0x08, 0x04, 0x35, 0x4B],
     0x874B0533, 0x31070921),

    ([0x24, 0xC3, 0x77, 0xDA, 0x84, 0x1A, 0x17, 0x99, 0x2B, 0xFB],
     0xE943FB13, 0xA12F2BB3),

    ([0x80, 0xA9, 0x49, 0x0E, 0xB1, 0xCD, 0xBF, 0xFD, 0x83, 0xA8, 0x7B],
     0x377B9DB1, 0xCF8FFB89)
]

for i, (data, low, high) in enumerate(strings, 1):
    key = low | (high << 32)

    decoded = bytes(
        value ^ ((key >> ((pos % 8) * 8)) & 0xFF)
        for pos, value in enumerate(data)
    )

    value = decoded.split(b"\0")[0]

    print(f"String {i}: {decoded}")

    if value.isdigit():
        print(f"DWORD: {int(value)}")
    else:
        print("ERRO: resultado não é decimal")

    print()
